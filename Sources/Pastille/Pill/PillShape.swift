import SwiftUI

/// Silhouette de la pastille : bord supérieur pleine largeur qui se creuse vers l'intérieur,
/// puis coins inférieurs arrondis. Les deux rayons sont animables.
struct PillShape: Shape {
    var topCornerRadius: CGFloat
    var bottomCornerRadius: CGFloat

    var animatableData: AnimatablePair<CGFloat, CGFloat> {
        get { .init(topCornerRadius, bottomCornerRadius) }
        set {
            topCornerRadius = newValue.first
            bottomCornerRadius = newValue.second
        }
    }

    func path(in rect: CGRect) -> Path {
        let t = topCornerRadius
        let b = bottomCornerRadius
        var p = Path()
        p.move(to: CGPoint(x: rect.minX, y: rect.minY))
        p.addQuadCurve(to: CGPoint(x: rect.minX + t, y: rect.minY + t),
                       control: CGPoint(x: rect.minX + t, y: rect.minY))
        p.addLine(to: CGPoint(x: rect.minX + t, y: rect.maxY - b))
        p.addQuadCurve(to: CGPoint(x: rect.minX + t + b, y: rect.maxY),
                       control: CGPoint(x: rect.minX + t, y: rect.maxY))
        p.addLine(to: CGPoint(x: rect.maxX - t - b, y: rect.maxY))
        p.addQuadCurve(to: CGPoint(x: rect.maxX - t, y: rect.maxY - b),
                       control: CGPoint(x: rect.maxX - t, y: rect.maxY))
        p.addLine(to: CGPoint(x: rect.maxX - t, y: rect.minY + t))
        p.addQuadCurve(to: CGPoint(x: rect.maxX, y: rect.minY),
                       control: CGPoint(x: rect.maxX - t, y: rect.minY))
        p.closeSubpath()
        return p
    }
}

/// Courbes d'animation communes, réglées pour imiter la Dynamic Island :
/// un ressort qui dépasse légèrement à l'ouverture, plus amorti à la fermeture.
enum PillAnimation {
    static let expand = Animation.spring(duration: 0.5, bounce: 0.3)
    static let collapse = Animation.spring(duration: 0.42, bounce: 0.18)
    static let activity = Animation.spring(duration: 0.45, bounce: 0.25)
}
